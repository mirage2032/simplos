// Display mode requested from the firmware, generated by `build.rs` from
// `SIMPLOS_FB_WIDTH` / `SIMPLOS_FB_HEIGHT` (default 1920x1080). The UEFI path
// honours it through `BOOTLOADER_CONFIG` below; the BIOS path can't see the
// kernel config at all, so the vendored bootloader's stage-2 reads the same two
// variables at build time. Changing one no longer silently desyncs the other.
include!(concat!(env!("OUT_DIR"), "/framebuffer.rs"));

/// Where the kernel image is loaded: the top 2 GiB, as is conventional on x86-64.
/// `tools/boot/build.rs` repeats it for the debugger scripts.
pub const KERNEL_BASE: u64 = 0xFFFF_FFFF_8000_0000;

// `frame_buffer` is deprecated in favour of configuring the mode when the disk
// image is created. That is the wrong place for this kernel: the request has to
// travel with the kernel so that `cargo run`, the released images and the
// browser build all ask for the same thing, and so the BIOS stage-2 cap
// generated from the same two variables cannot drift away from it.
//
// The kernel lives entirely in the upper half of the address space, so the
// lower half (PML4 entries 0-255) is left for user programs and every process
// can share one set of kernel mappings:
//
//   0xFFFF_8000_0000_0000  all of physical memory      memory::PHYS_MAP_BASE
//   (next free entries)    kernel stack, boot info,    placed by the bootloader
//                          framebuffer, ramdisk
//   0xFFFF_C000_0000_0000  heap                        allocator::HEAP_START
//   0xFFFF_D000_0000_0000  kernel thread stacks        memory::STACKS_START
//   0xFFFF_FFFF_8000_0000  kernel image                KERNEL_BASE
#[allow(deprecated)]
pub static BOOTLOADER_CONFIG: BootloaderConfig = {
    let mut config = BootloaderConfig::new_default();
    config.mappings.physical_memory = Some(Mapping::FixedAddress(memory::PHYS_MAP_BASE));
    config.mappings.kernel_base = Mapping::FixedAddress(KERNEL_BASE);
    // Whatever the bootloader places itself goes between the physical map and
    // the heap, which it doesn't know about.
    config.mappings.dynamic_range_start = Some(memory::PHYS_MAP_BASE);
    config.mappings.dynamic_range_end = Some(allocator::HEAP_START as u64 - 1);
    config.frame_buffer.minimum_framebuffer_width = Some(FRAMEBUFFER_WIDTH);
    config.frame_buffer.minimum_framebuffer_height = Some(FRAMEBUFFER_HEIGHT);
    config
};

/// Firmware the bootloader handed us off from.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum BootMode {
    Uefi,
    Bios,
    Unknown,
}

impl BootMode {
    pub fn as_str(self) -> &'static str {
        match self {
            BootMode::Uefi => "UEFI",
            BootMode::Bios => "BIOS",
            BootMode::Unknown => "unknown",
        }
    }
}

static BOOT_MODE: AtomicU8 = AtomicU8::new(BootMode::Unknown as u8);

/// Boot mode detected during `pre_init`.
pub fn boot_mode() -> BootMode {
    match BOOT_MODE.load(Ordering::Relaxed) {
        x if x == BootMode::Uefi as u8 => BootMode::Uefi,
        x if x == BootMode::Bios as u8 => BootMode::Bios,
        _ => BootMode::Unknown,
    }
}

static RAMDISK: spin::Once<&'static [u8]> = spin::Once::new();

/// The ramdisk the bootloader loaded beside the kernel, which for now is the
/// user program `user/probe`. `None` if the image was built without one.
pub fn ramdisk() -> Option<&'static [u8]> {
    RAMDISK.get().copied()
}

/// The boot info carries no firmware field, but the memory map does: regions the
/// bootloader could not classify keep their origin tag, which only one of the two
/// firmware paths ever produces.
fn detect_boot_mode(regions: &MemoryRegions) -> BootMode {
    for region in regions.iter() {
        match region.kind {
            MemoryRegionKind::UnknownUefi(_) => return BootMode::Uefi,
            MemoryRegionKind::UnknownBios(_) => return BootMode::Bios,
            _ => {}
        }
    }
    BootMode::Unknown
}

pub fn pre_init(boot_info: &'static mut BootInfo) {
    {
        init_io();
        BOOT_MODE.store(detect_boot_mode(&boot_info.memory_regions) as u8, Ordering::Relaxed);
        let phys_mem_offset = VirtAddr::new(
            boot_info.physical_memory_offset.take().expect("No physical memory offset found"),
        );
        let mut mapper = unsafe { memory::init(phys_mem_offset) };
        // After `init_io`: the bootloader's GDT, which lives down there, is no
        // longer the one loaded.
        memory::clear_lower_half(&mut mapper);
        let mut frame_allocator =
            unsafe { BootInfoFrameAllocator::init(&boot_info.memory_regions) };
        let screen = boot_info.framebuffer.as_ref().map_or(0, |fb| fb.info().byte_len);
        let heap = allocator::heap_size(frame_allocator.memory().0, screen);
        allocator::init_heap(&mut mapper, &mut frame_allocator, heap)
            .expect("heap initialization failed");
        frame_allocator.count_holders();
        *memory::FRAMES.lock() = Some(frame_allocator);
        *memory::PAGE_TABLE.lock() = Some(mapper);
        // Needs the page table for the idle thread's stack, and must be done
        // before interrupts are on: the first tick may want to switch threads.
        thread::init();
        process::init();

        // Initialize display with framebuffer
        let fb = boot_info.framebuffer.take().expect("No framebuffer found");
        // The host may have asked for a smaller mode than the firmware gave us;
        // `resolve_mode` applies it and reports what we actually ended up with.
        let info = video::resolve_mode(fb.info());
        video::init_display(fb, info);
        // Announce the mode we actually got. Under an emulator this is often the
        // only output that reaches the outside, and it is how you tell whether a
        // resolution change really took effect rather than silently falling back.
        serial_println!(
            "simplos: boot={} fb={}x{} stride={} bpp={} fmt={:?}",
            boot_mode().as_str(),
            info.width,
            info.height,
            info.stride,
            info.bytes_per_pixel,
            info.pixel_format
        );

        if let Some(addr) = boot_info.ramdisk_addr.into_option() {
            let len = boot_info.ramdisk_len as usize;
            // Safety: the bootloader mapped `len` bytes there, for the kernel
            // alone, and nothing unmaps them.
            RAMDISK.call_once(|| unsafe { core::slice::from_raw_parts(addr as *const u8, len) });
            serial_println!("simplos: ramdisk {} bytes", len);
        }

        // Initialize HPET for high-precision timing
        if let Some(rsdp_addr) = boot_info.rsdp_addr.take()
            && let Err(e) = io::hpet::init_hpet(rsdp_addr, phys_mem_offset)
        {
            // HPET init failed, continue without it
            serial_println!("HPET init failed: {}", e);
        }
        time::init();

        io::disk::init();

        x86_64::instructions::interrupts::enable();
    }
}

#[cfg(test)]
bootloader_api::entry_point!(test_kernel_main, config = &BOOTLOADER_CONFIG);
#[cfg(test)]
fn test_kernel_main(boot_info: &'static mut BootInfo) -> ! {
    pre_init(boot_info);
    fs::init();
    test_main();
    hlt_loop()
}

pub trait Testable {
    fn run(&self) -> ();
}
impl<T> Testable for T
where
    T: Fn(),
{
    fn run(&self) {
        serial_print!("{}...\t", core::any::type_name::<T>());
        let limit = TEST_LIMIT_SECONDS * u64::from(io::interrupts::pit::TIMER_HZ);
        TEST_DEADLINE.store(thread::ticks() + limit, Ordering::Relaxed);
        self();
        TEST_DEADLINE.store(0, Ordering::Relaxed);
        serial_println!("[ok]");
    }
}

/// How long one test may take before it's taken to hang. The slowest takes
/// under 5 s under emulation; much past that, it's waiting for what won't
/// come.
const TEST_LIMIT_SECONDS: u64 = 30;

/// The tick the test running has to be done by; 0 between tests.
static TEST_DEADLINE: AtomicU64 = AtomicU64::new(0);

/// Give the test running `seconds` more than `TEST_LIMIT_SECONDS`: for the
/// few that do a lot under emulation, as compiling with GCC does.
pub fn take_longer(seconds: u64) {
    let deadline = TEST_DEADLINE.load(Ordering::Relaxed);
    if deadline != 0 {
        let more = seconds * u64::from(io::interrupts::pit::TIMER_HZ);
        TEST_DEADLINE.store(deadline + more, Ordering::Relaxed);
    }
}

/// Called as the timer ticks: a test past its deadline fails there and then,
/// rather than hanging until boot-test gives up on its kernel.
pub fn check_test_deadline(now: u64) {
    let deadline = TEST_DEADLINE.load(Ordering::Relaxed);
    if deadline != 0 && now >= deadline {
        serial_println!("[failed]\n");
        serial_println!("Error: not done after {} s, or as long as it asked\n", TEST_LIMIT_SECONDS);
        exit_qemu(QemuExitCode::Failed);
    }
}

pub fn test_runner(tests: &[&dyn Testable]) {
    serial_println!("Running {} tests", tests.len());
    for test in tests {
        test.run();
    }
    fs::unmount();
    exit_qemu(QemuExitCode::Success);
}

pub fn test_panic_handler(info: &PanicInfo) -> ! {
    serial_println!("[failed]\n");
    serial_println!("Error: {}\n", info);
    exit_qemu(QemuExitCode::Failed);
    hlt_loop()
}
#[cfg(test)]
#[panic_handler]
fn panic(info: &PanicInfo) -> ! {
    test_panic_handler(info)
}

pub fn hlt_loop() -> ! {
    loop {
        x86_64::instructions::hlt();
    }
}
